import argparse
from dataclasses import fields
import difflib
import json
from pathlib import Path
import re
from typing import Sequence

from lib.commands import reject_forbidden
from lib.models import Project, Repository, load_inventory


POLICY_ROOT = Path(__file__).resolve().parents[1]
INVENTORY_PATH = POLICY_ROOT / "repositories.json"
TEMPLATE_PATH = POLICY_ROOT / "templates" / "dependency-gate.yml.tmpl"
POLICY_SHA_PATTERN = re.compile(r"[0-9a-f]{40}")
PROJECT_KEYS = {
    field.name: field.name.replace("_", "-")
    for field in fields(Project)
}
AUTO_MERGE_JOB = """
  dependabot-auto-merge:
    if: github.event.pull_request.user.login == 'dependabot[bot]'
    needs: dependency-gate
    permissions:
      contents: write
      pull-requests: write
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - name: Fetch Dependabot metadata
        id: dependabot-metadata
        uses: dependabot/fetch-metadata@08eff52bf64351f401fb50d4972fa95b9f2c2d1b
        with:
          github-token: ${{ secrets.GITHUB_TOKEN }}
      - name: Approve and enable auto-merge
        if: >-
          steps.dependabot-metadata.outputs.update-type == 'version-update:semver-patch' ||
          steps.dependabot-metadata.outputs.update-type == 'version-update:semver-minor'
        env:
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
          PR_URL: ${{ github.event.pull_request.html_url }}
        run: |
          gh pr review --approve "$PR_URL"
          gh pr merge --auto --squash "$PR_URL"
      - name: Require manual review for other update types
        if: >-
          steps.dependabot-metadata.outputs.update-type != 'version-update:semver-patch' &&
          steps.dependabot-metadata.outputs.update-type != 'version-update:semver-minor'
        env:
          UPDATE_TYPE: ${{ steps.dependabot-metadata.outputs.update-type }}
        run: |
          {
            echo "## Manual review required"
            echo
            echo "Dependabot update type '$UPDATE_TYPE' is not eligible for auto-merge."
          } >> "$GITHUB_STEP_SUMMARY"
""".rstrip("\n")


def _project_payload(project: Project) -> dict[str, str | int]:
    return {
        PROJECT_KEYS[field.name]: value
        for field in fields(Project)
        if (value := getattr(project, field.name)) is not None
    }


def render_caller(repository: Repository, policy_sha: str) -> str:
    if POLICY_SHA_PATTERN.fullmatch(policy_sha) is None:
        raise ValueError("policy SHA must be exactly 40 lowercase hexadecimal characters")

    projects_json = json.dumps(
        [_project_payload(project) for project in repository.projects],
        separators=(",", ":"),
    ).replace("'", "''")
    template = TEMPLATE_PATH.read_text()
    rendered = (
        template
        .replace("POLICY_COMMIT_SHA", policy_sha)
        .replace("AUTO_MERGE_JOB", AUTO_MERGE_JOB if repository.auto_merge_enabled else "")
        .replace("COMPACT_PROJECT_JSON", projects_json)
    )
    reject_forbidden(rendered)
    return rendered


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Render a repository dependency-gate caller")
    parser.add_argument("--repository", required=True, help="repository name in repositories.json")
    parser.add_argument("--policy-sha", required=True, help="40-character lowercase policy commit SHA")
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--output", type=Path, help="write the generated caller to this path")
    destination.add_argument("--check", type=Path, help="compare this path with generated bytes")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    repository = load_inventory(INVENTORY_PATH).repository(args.repository)
    generated = render_caller(repository, args.policy_sha).encode()

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(generated)
        return 0

    target = args.check
    assert target is not None
    actual = target.read_bytes() if target.is_file() else b""
    if actual == generated:
        return 0

    diff = difflib.unified_diff(
        actual.decode(errors="replace").splitlines(keepends=True),
        generated.decode().splitlines(keepends=True),
        fromfile=str(target),
        tofile=f"{target} (generated)",
    )
    print("".join(diff), end="")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
